-- 1. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    customer_address TEXT NOT NULL,
    customer_city TEXT NOT NULL,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0,
    delivery_fee NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
    notes TEXT DEFAULT ''
);

-- Index for searching and sorting orders
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders (status);
CREATE INDEX IF NOT EXISTS idx_orders_phone ON public.orders (customer_phone);

-- 2. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    name TEXT NOT NULL,
    name_ar TEXT NOT NULL,
    description TEXT NOT NULL,
    description_ar TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    original_price NUMERIC(10, 2),
    image TEXT NOT NULL DEFAULT '/logo.jpg',
    category TEXT NOT NULL,
    category_ar TEXT NOT NULL,
    in_stock INTEGER NOT NULL DEFAULT 10,
    featured BOOLEAN NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_products_category ON public.products (category);
CREATE INDEX IF NOT EXISTS idx_products_featured ON public.products (featured);

-- 3. ROW LEVEL SECURITY (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- Allow anonymous users to place orders
CREATE POLICY "Allow public order placement" 
ON public.orders FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- Allow service role and dashboard full access to orders
CREATE POLICY "Allow full access for service role on orders" 
ON public.orders FOR ALL 
TO service_role 
USING (true) 
WITH CHECK (true);

-- Allow public read access to products
CREATE POLICY "Allow public read access on products" 
ON public.products FOR SELECT 
TO anon, authenticated 
USING (true);

-- Allow service role to manage products
CREATE POLICY "Allow service role full access on products" 
ON public.products FOR ALL 
TO service_role 
USING (true) 
WITH CHECK (true);

